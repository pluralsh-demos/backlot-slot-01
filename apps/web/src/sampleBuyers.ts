/** Picks a buyer at random, skipping `avoidIndex` when another option exists. */
export function pickSampleBuyer(avoidIndex?: number): { buyer: SampleBuyer; index: number } {
  const count = sampleBuyers.length;
  let index = Math.floor(Math.random() * count);
  if (avoidIndex !== undefined && count > 1 && index === avoidIndex) {
    index = (index + 1 + Math.floor(Math.random() * (count - 1))) % count;
  }
  const buyer = sampleBuyers[index];
  if (buyer === undefined) throw new Error("sampleBuyers is empty");
  return { buyer, index };
}
